JUN1 = date(2026, 6, 1)  # a Monday


def d(result, aid: str) -> tuple[date, date]:  # type: ignore[no-untyped-def]
    """(start, last day worked) for an activity -- the human-readable span."""
    return day_of(result.early_start[aid]), day_of(result.early_finish[aid] - 1)


# -- the basics -----------------------------------------------------------


def test_a_single_five_day_task_runs_monday_to_friday(five_day) -> None:  # type: ignore[no-untyped-def]
    result = calculate([Task("A", "Excavate", 5, "5D")], [], {"5D": five_day}, data_date=JUN1)
    assert d(result, "A") == (date(2026, 6, 1), date(2026, 6, 5))
    assert result.total_float_days["A"] == 0
    assert result.is_critical("A")


def test_a_chain_of_three_is_the_sum_of_its_durations(five_day) -> None:  # type: ignore[no-untyped-def]
    """A(3) -> B(2) -> C(4) = 9 working days: Mon 1 Jun to Thu 11 Jun."""
    tasks = [Task("A", "", 3, "5D"), Task("B", "", 2, "5D"), Task("C", "", 4, "5D")]
    links = [Link("A", "B"), Link("B", "C")]
    result = calculate(tasks, links, {"5D": five_day}, data_date=JUN1)

    assert d(result, "A") == (date(2026, 6, 1), date(2026, 6, 3))
    assert d(result, "B") == (date(2026, 6, 4), date(2026, 6, 5))
    assert d(result, "C") == (date(2026, 6, 8), date(2026, 6, 11))  # skips the weekend
    assert result.critical_ids == ["A", "B", "C"]
    assert result.longest_path() == ["A", "B", "C"]


def test_a_parallel_branch_carries_float(five_day) -> None:  # type: ignore[no-untyped-def]
    """START -> {LONG(10), SHORT(4)} -> END. SHORT has six working days of float."""
    tasks = [
        Task("START", "", 1, "5D"),
        Task("LONG", "", 10, "5D"),
        Task("SHORT", "", 4, "5D"),
        Task("END", "", 1, "5D"),
    ]
    links = [
        Link("START", "LONG"),
        Link("START", "SHORT"),
        Link("LONG", "END"),
        Link("SHORT", "END"),
    ]
    result = calculate(tasks, links, {"5D": five_day}, data_date=JUN1)

    assert result.total_float_days["LONG"] == 0
    assert result.total_float_days["SHORT"] == 6
    assert result.free_float_days["SHORT"] == 6
    assert result.longest_path() == ["START", "LONG", "END"]
    assert result.is_critical("SHORT") is False


def test_free_float_is_smaller_than_total_float_on_a_shared_path(five_day) -> None:  # type: ignore[no-untyped-def]
    """A -> B -> END, with END also driven by a longer branch.

    A and B each have total float, but only B has free float: A's slack is
    B's to spend, not A's.
    """
    tasks = [
        Task("A", "", 2, "5D"),
        Task("B", "", 2, "5D"),
        Task("LONG", "", 10, "5D"),
        Task("END", "", 1, "5D"),
    ]
    links = [Link("A", "B"), Link("B", "END"), Link("LONG", "END")]
    result = calculate(tasks, links, {"5D": five_day}, data_date=JUN1)

    assert result.total_float_days["A"] == 6
    assert result.total_float_days["B"] == 6
    assert result.free_float_days["A"] == 0  # spending it would delay B
    assert result.free_float_days["B"] == 6


# -- the four relationship types ------------------------------------------


def test_all_four_relationship_types_by_hand(five_day) -> None:  # type: ignore[no-untyped-def]
    """P runs Mon 1 to Fri 5 June. Each successor is 2 days on the same calendar.

    FS: starts after P finishes           -> Mon 8, Tue 9
    SS: starts when P starts              -> Mon 1, Tue 2
    FF: finishes when P finishes          -> Thu 4, Fri 5
    SF: finishes when P starts            -> the finish is bounded at Mon 1, so
        the work is Thu 28 May to Fri 29 May -- but the data date floors it to
        Mon 1 June, which is the correct and more useful answer.
    """
    cals = {"5D": five_day}
    p = Task("P", "", 5, "5D")

    fs = calculate(
        [p, Task("S", "", 2, "5D")], [Link("P", "S", RelationType.FS)], cals, data_date=JUN1
    )
    assert d(fs, "S") == (date(2026, 6, 8), date(2026, 6, 9))

    ss = calculate(
        [p, Task("S", "", 2, "5D")], [Link("P", "S", RelationType.SS)], cals, data_date=JUN1
    )
    assert d(ss, "S") == (date(2026, 6, 1), date(2026, 6, 2))

    ff = calculate(
        [p, Task("S", "", 2, "5D")], [Link("P", "S", RelationType.FF)], cals, data_date=JUN1
    )
    assert d(ff, "S") == (date(2026, 6, 4), date(2026, 6, 5))

    sf = calculate(
        [p, Task("S", "", 2, "5D")], [Link("P", "S", RelationType.SF)], cals, data_date=JUN1
    )
    # Floored by the data date rather than scheduled into the past.
    assert d(sf, "S")[0] == date(2026, 6, 1)


def test_a_lag_pushes_the_successor_out(five_day) -> None:  # type: ignore[no-untyped-def]
    """A(2) finishes Tue 2 Jun. FS+3 working days -> B starts Fri 5 Jun."""
    tasks = [Task("A", "", 2, "5D"), Task("B", "", 1, "5D")]
