def test_as_late_as_possible_consumes_free_float_without_moving_the_finish(
    five_day,
) -> None:  # type: ignore[no-untyped-def]
    """SHORT slides right to meet END, and the project finish does not move."""
    links = [
        Link("START", "LONG"),
        Link("START", "SHORT"),
        Link("LONG", "END"),
        Link("SHORT", "END"),
    ]

    def build(short_constraint: ConstraintType) -> list[Task]:
        return [
            Task("START", "", 1, "5D"),
            Task("LONG", "", 10, "5D"),
            Task("SHORT", "", 4, "5D", constraint=short_constraint),
            Task("END", "", 1, "5D"),
        ]

    plain = calculate(build(ConstraintType.NONE), links, {"5D": five_day}, data_date=JUN1)
    alap = calculate(
        build(ConstraintType.AS_LATE_AS_POSSIBLE), links, {"5D": five_day}, data_date=JUN1
    )

    # Without the constraint SHORT runs as early as it can: Tue 2 to Fri 5 June.
    assert d(plain, "SHORT") == (date(2026, 6, 2), date(2026, 6, 5))
    # With it, SHORT consumes its six days of free float and butts up against
    # END: Wed 10 to Mon 15 June.
    assert d(alap, "SHORT") == (date(2026, 6, 10), date(2026, 6, 15))
    # And the project finish has not moved, which is the whole point of ALAP.
    assert alap.project_finish == plain.project_finish


