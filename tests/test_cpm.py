def test_retained_logic_and_progress_override_give_different_answers(five_day) -> None:  # type: ignore[no-untyped-def]
    """The out-of-sequence case, both ways, hand-computed.

    A(10) planned 1-12 June is still running with 8 days left. B(5) started early
    on 8 June and has 5 days left. Data date is Mon 15 June.

    * Retained logic: B still waits for A. A's remaining 8 days run 15-24 June,
      so B runs 25 June - 1 July.
    * Progress override: the link is dropped, B's remaining work starts at the
      data date, 15 June, and finishes 19 June.
    """
    tasks = [
        Task("A", "", 10, "5D", actual_start=date(2026, 6, 1), remaining_days=8),
        Task("B", "", 5, "5D", actual_start=date(2026, 6, 8), remaining_days=5),
    ]
    links = [Link("A", "B")]
    dd = date(2026, 6, 15)

    retained = calculate(
        tasks,
        links,
        {"5D": five_day},
        data_date=dd,
        options=SchedulerOptions(progress_mode=ProgressMode.RETAINED_LOGIC),
    )
    override = calculate(
        tasks,
        links,
        {"5D": five_day},
        data_date=dd,
        options=SchedulerOptions(progress_mode=ProgressMode.PROGRESS_OVERRIDE),
    )

    assert d(retained, "A") == (date(2026, 6, 15), date(2026, 6, 24))
    assert d(retained, "B") == (date(2026, 6, 25), date(2026, 7, 1))
    assert d(override, "B") == (date(2026, 6, 15), date(2026, 6, 19))
    assert retained.project_finish != override.project_finish

    # Progress override must say what it dropped. A mode that silently removes
    # logic is indistinguishable from a bug.
    assert len(override.suppressed_links) == 1
    assert override.suppressed_links[0].predecessor == "A"
    assert retained.suppressed_links == ()


# -- driving path ----------------------------------------------------------


def test_the_driving_path_is_stable_when_the_input_is_shuffled(five_day) -> None:  # type: ignore[no-untyped-def]
    """The source engine's greedy forward walk fails this. Ours must not."""
    tasks = [
        Task("START", "", 1, "5D"),
        Task("L1", "", 5, "5D"),
        Task("L2", "", 5, "5D"),
        Task("R1", "", 3, "5D"),
        Task("END", "", 1, "5D"),
    ]
    links = [
        Link("START", "L1"),
        Link("L1", "L2"),
        Link("L2", "END"),
        Link("START", "R1"),
        Link("R1", "END"),
    ]
    first = calculate(tasks, links, {"5D": five_day}, data_date=JUN1).longest_path()
    for rotation in range(1, len(tasks)):
        shuffled = tasks[rotation:] + tasks[:rotation]
        again = calculate(shuffled, links, {"5D": five_day}, data_date=JUN1).longest_path()
        assert again == first, f"rotation {rotation} changed the driving path"
    assert first == ["START", "L1", "L2", "END"]


def test_two_equally_critical_branches_return_one_stable_named_chain(five_day) -> None:  # type: ignore[no-untyped-def]
    tasks = [
        Task("START", "", 1, "5D"),
        Task("A", "", 5, "5D"),
        Task("B", "", 5, "5D"),
        Task("END", "", 1, "5D"),
    ]
    links = [Link("START", "A"), Link("A", "END"), Link("START", "B"), Link("B", "END")]
    runs = {
        tuple(calculate(tasks, links, {"5D": five_day}, data_date=JUN1).longest_path())
        for _ in range(5)
    }
    assert len(runs) == 1
    path = next(iter(runs))
    assert path[0] == "START" and path[-1] == "END"
    assert len(path) == 3


