    tasks = [Task("A", "", 1, "5D"), Task("B", "", 1, "5D"), Task("C", "", 1, "5D")]
    links = [Link("A", "B"), Link("B", "C"), Link("C", "A")]
    with pytest.raises(ScheduleCycleError) as excinfo:
        calculate(tasks, links, {"5D": five_day}, data_date=JUN1)
    assert set(excinfo.value.cycle) == {"A", "B", "C"}


